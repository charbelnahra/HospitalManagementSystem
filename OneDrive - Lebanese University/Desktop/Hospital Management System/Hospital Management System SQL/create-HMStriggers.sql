CREATE TRIGGER TRG_DEPARTMENTS_FORMAT
ON DEPARTMENTS
AFTER INSERT, UPDATE
AS
BEGIN
    UPDATE DEPARTMENTS
    SET DEPARTMENT_NAME = UPPER(DEPARTMENT_NAME)
    WHERE DEPARTMENT_ID IN (SELECT DEPARTMENT_ID FROM inserted);
END;
GO


CREATE TRIGGER TRG_PATIENTS_EMAIL_FORMAT
ON PATIENTS
AFTER INSERT, UPDATE
AS
BEGIN
    UPDATE PATIENTS
    SET EMAIL = LOWER(EMAIL)
    WHERE PATIENT_ID IN (SELECT PATIENT_ID FROM inserted);
END;
GO


