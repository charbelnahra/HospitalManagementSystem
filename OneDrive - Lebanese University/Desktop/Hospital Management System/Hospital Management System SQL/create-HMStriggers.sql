CREATE TRIGGER TRG_DEPARTMENTS_NO_DELETE
ON DEPARTMENTS
INSTEAD OF DELETE
AS
BEGIN
    IF EXISTS (
        SELECT 1 
        FROM DOCTORS 
        WHERE DEPID IN (SELECT DEPARTMENT_ID FROM deleted)
    )
    BEGIN
        RAISERROR ('Cannot delete department: Doctors assigned to it.', 16, 1);
        RETURN;
    END

    DELETE FROM DEPARTMENTS
    WHERE DEPARTMENT_ID IN (SELECT DEPARTMENT_ID FROM deleted);
END;
GO


